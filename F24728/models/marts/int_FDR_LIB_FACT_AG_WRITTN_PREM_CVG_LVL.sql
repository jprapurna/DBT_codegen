            GEOS.ST_NM, 
            GEOS.ST_CD, 
            RGEO.GRGNG_ZIP_5, 
            SUM(COALESCE(FACT.TTL_WRITTN_PREM_AMT,0)) TTL_WRITTN_PREM_AMT, 
            SUM(COALESCE(FACT.CVG_EXPS_VAL,0)) CVG_EXPS_VAL, 
