            JOIN {{ source('AGDM', 'DIM_DT') }} FISCPER ON FACT.FISC_PER_SK =FISCPER.DT_SK
            JOIN {{ source('AGDM', 'DIM_AG_HH') }} HH ON HH.HH_SK=FACT.HH_SK
        WHERE 
            1 = 1 
            AND TRIM(GEOS.ST_NM) NOT IN ({{ var('GEO_ST_NM') }})
            AND (CASE WHEN {{ var('RUN_TYPE') }} = 'Register' THEN REGPER.CLNDR_YR ELSE FISCPER.CLNDR_YR END) = {{ var('RPT_YEAR') }}
            AND AGDM.DIM_AG_TRANS_TYP_PLCY.TRANS_TYP_PLCY_CD NOT IN ('WO')
            AND (TTL_WRITTN_PREM_AMT !=0 AND CVG_EXPS_VAL!=0)
        GROUP BY 
            REGPER.CLNDR_YR, FISCPER.CLNDR_YR, PLCY.PLCY_CNTRCT_NUM, MPLCY.BI_LMT, MPLCY.FA2_PLCY_IND, MPLCY.RATNG_CMPY_CD, EPLCY.NAIC_CMPY_CD, EPLCY.PHY_DMG_IND, EPLCY.NY_SSL_IND, EPLCY.GA_UMBI_PD_ADDED_IND, SOI.DRVR_TRNG_IND, SOI.SOI_TYP, SOI.VEH_MDL_YR, SOI.SNR_DRVR_IND, SOI.UNIT_NUM, ESOI.UM_UIM_STACKING, ESOI.PIP_WVR_WL_IND, ESOI.PIP_MED_SEC_IND, ESOI.PIP_LOSS_INCOME_IND, ESOI.MI_PPO_IND, ESOI.PRD_GRP_CD, ESOI.NJ_HLTH_INSR_PRIM, ESOI.NJ_EXTR_PIP_PKG, ESOI.NJ_RESDNC_RLTNSHP_PIP_IND, ESOI.NY_FULL_CVG_GLASS_COMP_IND, ESOI.NJ_NO_LWST_LMT_IND, ESOI.NJ_NMD_DRVR_EXCL_IND, ESOI.RT_CLS, ESOI.AGE, ESOI.GENDR, ESOI.MRTL_STAT, ESOI.AUTO_USE_CD, ESOI.MILES_TO_WRK, ESOI.NJ_EXCPTION_CD, ESOI.PASSV_RESTRA_DISC, ESOI.DEFNS_DRVR_DISC_IND, ESOI.ANTI_THFT_DISC, ESOI.DAY_TM_RUN_LIGHTS, ESOI.LMT_TORT, ESOI.COMP_DED, MSOI.MLT_CAR_IND, MSOI.GOOD_STDNT_IND, MSOI.COLL_DED, CVG.ACCTNG_LOB, CVG.CVG_TYP_CD, ECVG.EFF_DT, ECVG.NJ_RTD_PNTS, ECVG.NJ_FRGVN_PNTS, ECVG.CVG_TYP_IND, MCVG.CVG_AMT, GEOS.ST_NM, GEOS.ST_CD, RGEO.GRGNG_ZIP_5, HH.NUM_OF_CARS_IN_HH, ESOI.RDRVR_DT_OF_BRTH, PLCY.TERM_STRT_DT, PLCY.SRC_SYS_CD, PLCY.PNI_AGE
