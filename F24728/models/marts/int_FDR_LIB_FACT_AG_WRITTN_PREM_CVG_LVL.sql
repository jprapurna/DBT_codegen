        NJ_NMD_DRVR_EXCL_IND, 
        GRGNG_ZIP_5, 
        RATNG_CMPY_CD, 
        MLT_CAR_IND, 
        RT_CLS, 
        AGE, 
        GENDR, 
        MRTL_STAT, 
        AUTO_USE_CD, 
        MILES_TO_WRK, 
        GOOD_STDNT_IND, 
        DRVR_TRNG_IND, 
        SOI_TYP, 
        PHY_DMG_IND, 
        NJ_RTD_PNTS, 
        VEH_MDL_YR, 
        NJ_EXCPTION_CD, 
        NJ_FRGVN_PNTS, 
        PASSV_RESTRA_DISC, 
        SNR_DRVR_IND, 
        DEFNS_DRVR_DISC_IND, 
        ANTI_THFT_DISC, 
        DAY_TM_RUN_LIGHTS, 
        LMT_TORT, 
        CVG_TYP_IND, 
        CVG_EXPS_VAL, 
        TTL_WRITTN_PREM_AMT, 
        COMP_DED, 
        COLL_DED, 
        LTRIM(RTRIM(PLCY_CNTRCT_NUM)) AS PLCY_CNTRCT_NUM, 
        UNIT_NUM, 
        EFF_DT, 
        NUM_OF_CARS_IN_HH, 
        RDRVR_DT_OF_BRTH, 
        TERM_STRT_DT, 
        COALESCE(SRC_SYS_CD,'') as SRC_SYS_CD, 
        PNI_AGE
    FROM (
        SELECT 
            REGPER.CLNDR_YR REG_PER_YR, 
            FISCPER.CLNDR_YR FISC_PER_YR, 
            PLCY.PLCY_CNTRCT_NUM, 
            MPLCY.BI_LMT, 
            MPLCY.FA2_PLCY_IND, 
            MPLCY.RATNG_CMPY_CD, 
            EPLCY.NAIC_CMPY_CD, 
            EPLCY.PHY_DMG_IND, 
            EPLCY.NY_SSL_IND, 
            EPLCY.GA_UMBI_PD_ADDED_IND, 
            SOI.DRVR_TRNG_IND, 
            SOI.SOI_TYP, 
            SOI.VEH_MDL_YR, 
            SOI.SNR_DRVR_IND, 
            SOI.UNIT_NUM, 
            ESOI.UM_UIM_STACKING, 
            ESOI.PIP_WVR_WL_IND, 
            ESOI.PIP_MED_SEC_IND, 
            ESOI.PIP_LOSS_INCOME_IND, 
            ESOI.MI_PPO_IND, 
            ESOI.PRD_GRP_CD, 
            ESOI.NJ_HLTH_INSR_PRIM, 
