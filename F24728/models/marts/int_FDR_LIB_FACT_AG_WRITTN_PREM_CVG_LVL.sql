            ESOI.NJ_EXCPTION_CD, 
            ESOI.PASSV_RESTRA_DISC, 
            ESOI.DEFNS_DRVR_DISC_IND, 
            ESOI.ANTI_THFT_DISC, 
            ESOI.DAY_TM_RUN_LIGHTS, 
            ESOI.LMT_TORT, 
            ESOI.COMP_DED, 
            MSOI.MLT_CAR_IND, 
            MSOI.GOOD_STDNT_IND, 
            MSOI.COLL_DED, 
            CVG.ACCTNG_LOB, 
            CVG.CVG_TYP_CD, 
