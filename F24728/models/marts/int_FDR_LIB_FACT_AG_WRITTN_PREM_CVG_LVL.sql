            ESOI.RDRVR_DT_OF_BRTH, 
            PLCY.TERM_STRT_DT, 
            PLCY.SRC_SYS_CD, 
            PLCY.PNI_AGE
        FROM 
            {{ source('AGDM', 'FACT_AG_WRITTN_PREM_CVG_LVL') }} FACT
            JOIN {{ source('AGDM', 'DIM_AG_PLCY') }} PLCY ON FACT.PLCY_SK=PLCY.PLCY_SK
            JOIN {{ source('AGDM', 'DIM_AG_MINI_PLCY') }} MPLCY ON FACT.MINI_PLCY_SK = MPLCY.MINI_PLCY_SK
            JOIN {{ source('AGDM', 'DIM_AG_PLCY_ENH') }} EPLCY ON FACT.PLCY_ENH_SK = EPLCY.PLCY_ENH_SK
            JOIN {{ source('AGDM', 'DIM_AG_TRANS_TYP_PLCY') }} ON FACT.TRANS_TYP_PLCY_SK=AGDM.DIM_AG_TRANS_TYP_PLCY.TRANS_TYP_PLCY_SK
