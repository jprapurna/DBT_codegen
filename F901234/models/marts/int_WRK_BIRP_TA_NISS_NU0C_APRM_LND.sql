SELECT 
    REGSTR_CLS_MNTH, 
    FISC_PER_YR, 
    NAIC_CMPNY_CD, 
    NISS_CMPNY_CD, 
    STATE_NM, 
    STATE_CD, 
    ACCT_LOB, 
    CVG_CD, 
    CVG_AMT, 
    BI_LMT, 
    GA_UMBI_PD_ADDED_IND, 
    FA2_PLCY_IND, 
    UM_UIM_STACKING_IND, 
    PIP_WVR_WL_IND, 
    PIP_MED_SEC_IND, 
    PIP_LOSS_INCOME_IND, 
    MI_PPO_IND, 
    PRD_GRP_CD, 
    NJ_HLTH_INSR_PRIM, 
    NJ_EXTR_PIP_PKG, 
    NJ_RESDNC_RLTNSHP_PIP_IND, 
    NY_SSL_IND, 
    NY_FULL_CVG_GLASS_COMP_IND, 
    GRGNG_ZIP_5, 
    RATNG_CMPY_CD, 
    MLT_CAR_IND, 
    RT_CLS, 
    RTD_DRVR_AGE, 
    RTD_DRVR_GNDR_CD, 
    RTD_DRVR_MRTL_STAT, 
    AUTO_USE_CD, 
    MILES_TO_WRK, 
    GOOD_STDNT_IND, 
    DRVR_TRNG_IND, 
    SOI_TYP_CD, 
    PHY_DMG_IND, 
    NJ_RTD_PNTS, 
    VEH_YR, 
    NJ_EXCPTION_CD, 
    NJ_FRGVN_PNTS, 
    PASSV_RESTRA_DISC_IND, 
    SNR_DRVR_IND, 
    DEFNSV_DRVR_DISC_IND, 
    ANTI_THFT_DISC_IND, 
    DAY_TM_RUN_LIGHTS, 
    LMT_TORT, 
    CVG_TYP_IND, 
    EXPSR_MNTH_CNT, 
    WRITTN_PREM_AMT, 
    NJ_NO_LWST_LMT_IND, 
    NJ_NMD_DRVR_EXCL_IND, 
    COMP_DED, 
    COLL_DED, 
    PLCY_NUM, 
    UNIT_NUM, 
    EFF_DT, 
    NUM_OF_CARS_IN_HH, 
    RTD_DRVR_DOB, 
    PLCY_TRM_STRT_DT, 
    SRC_SYS_CD, 
    PNI_AGE, 
    MIS_LOB, 
    PRINCIPAL_OPRT, 
    SOURCE_IND_DERIVED
FROM (
    SELECT 
        TO_CHAR(REGSTR_CLS_MNTH) AS REGSTR_CLS_MNTH, 
        '' as FISC_PER_YR, 
        NAIC_CMPNY_CD, 
        CASE WHEN NAIC_CMPNY_CD='21687' THEN '176' WHEN NAIC_CMPNY_CD='44245' THEN '941' END AS NISS_CMPNY_CD, 
        TRIM(UPPER(STATE_NM)) AS STATE_NM, 
        FIG_STATE AS STATE_CD, 
        ACCT_LOB, 
        CVG_CD, 
        CVG_AMT, 
        BI_LMT, 
        GA_UMBI_PD_ADDED_IND, 
        '' as FA2_PLCY_IND, 
        UM_UIM_STACKING_IND, 
        NULL as PIP_WVR_WL_IND, 
        NULL as PIP_MED_SEC_IND, 
        NULL as PIP_LOSS_INCOME_IND, 
        NULL as MI_PPO_IND, 
        '' as PRD_GRP_CD, 
        '' as NJ_HLTH_INSR_PRIM, 
        '' as NJ_EXTR_PIP_PKG, 
        NULL as NJ_RESDNC_RLTNSHP_PIP_IND, 
        NULL as NY_SSL_IND, 
        NULL as NY_FULL_CVG_GLASS_COMP_IND, 
        GRGNG_ZIP_5, 
        '' as RATNG_CMPY_CD, 
        MLT_CAR_IND, 
        ''as RT_CLS, 
        RTD_DRVR_AGE, 
        RTD_DRVR_GNDR_CD, 
        CASE WHEN RTD_DRVR_MRTL_STAT='single' THEN 'S' WHEN RTD_DRVR_MRTL_STAT='married' THEN 'M' ELSE UPPER(RTD_DRVR_MRTL_STAT) END AS RTD_DRVR_MRTL_STAT, 
        AUTO_USE_CD, 
        '' as MILES_TO_WRK, 
        GOOD_STDNT_IND, 
        DRVR_TRNG_IND, 
        SOI_TYP_CD, 
        CASE WHEN PHY_DMG_IND='Y' THEN 1 WHEN PHY_DMG_IND='N' THEN 0 ELSE NULL END AS PHY_DMG_IND, 
        '' as NJ_RTD_PNTS, 
        try_to_number(VEH_YR) as VEH_YR, 
        '' AS NJ_EXCPTION_CD, 
        '' AS NJ_FRGVN_PNTS, 
        PASSV_RESTRA_DISC_IND, 
        '' AS SNR_DRVR_IND, 
        CASE WHEN DEFNSV_DRVR_DISC_IND='Y' THEN 1 WHEN DEFNSV_DRVR_DISC_IND='N' THEN 0 ELSE NULL END AS DEFNSV_DRVR_DISC_IND, 
        ANTI_THFT_DISC_IND, 
        '' as DAY_TM_RUN_LIGHTS, 
        '' as LMT_TORT, 
        CVG_TYP_IND, 
        SUM(EXPSR_MNTH_CNT) AS EXPSR_MNTH_CNT, 
        SUM(WRITTN_PREM_AMT) as WRITTN_PREM_AMT, 
        NULL as NJ_NO_LWST_LMT_IND, 
        NULL as NJ_NMD_DRVR_EXCL_IND, 
        COMP_DED, 
        COLL_DED, 
        PLCY_NUM, 
        NULL as UNIT_NUM, 
        EFF_DT, 
        NULL AS NUM_OF_CARS_IN_HH, 
        RTD_DRVR_DOB, 
        PLCY_TRM_STRT_DT, 
        SRC_SYS_CD, 
        NULL AS PNI_AGE, 
        MIS_LOB, 
        '' as PRINCIPAL_OPRT, 
        'TOGGLE AUTO' AS SOURCE_IND_DERIVED
    FROM 
        {{ var('SCHEMA_FPR') }}.{{ var('FPR_TA_DA_CVG_LVL_STAT_TBL') }}
    WHERE 
        TRIM(UPPER(STATE_NM)) NOT IN ({{ var('GEO_ST_NM') }})
        AND SUBSTR(REGSTR_CLS_MNTH,1,4)={{ var('RPT_YEAR') }}
    GROUP BY 
        REGSTR_CLS_MNTH, NAIC_CMPNY_CD, TRIM(UPPER(STATE_NM)), FIG_STATE, ACCT_LOB, CVG_CD, CVG_AMT, BI_LMT, GA_UMBI_PD_ADDED_IND, PLCY_REWRIT_IND, UM_UIM_STACKING_IND, GRGNG_ZIP_5, MLT_CAR_IND, RTD_DRVR_AGE, RTD_DRVR_GNDR_CD, RTD_DRVR_MRTL_STAT, AUTO_USE_CD, GOOD_STDNT_IND, DRVR_TRNG_IND, SOI_TYP_CD, PHY_DMG_IND, VEH_YR, PASSV_RESTRA_DISC_IND, DEFNSV_DRVR_DISC_IND, ANTI_THFT_DISC_IND, CVG_TYP_IND, COMP_DED, COLL_DED, PLCY_NUM, EFF_DT, RTD_DRVR_DOB, PLCY_TRM_STRT_DT, SRC_SYS_CD, MIS_LOB
) 
WHERE WRITTN_PREM_AMT!=0